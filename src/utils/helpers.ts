export const jsonToGpx = (jsonData: any) => {
  const { MNTN_NM, PMNTN_NM } = jsonData.attributes;
  const coordinates = jsonData.geometry.paths[0];

  const gpxHeader = `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="CustomScript" xmlns="http://www.topografix.com/GPX/1/1">
  <metadata>
    <name>${MNTN_NM} - ${PMNTN_NM}</name>
  </metadata>
  <trk>
    <name>${MNTN_NM} - ${PMNTN_NM}</name>
    <trkseg>`;

  const gpxBody = coordinates
    .map(([lon, lat]) => `      <trkpt lon="${lon}" lat="${lat}"></trkpt>`)
    .join("\n");

  const gpxFooter = `
    </trkseg>
  </trk>
</gpx>`;

  return gpxHeader + "\n" + gpxBody + gpxFooter;
};


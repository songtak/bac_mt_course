import dayjs from "dayjs";
import { kor1 } from "../assets/kor1";
import { kor2 } from "../assets/kor2";
import "dayjs/locale/ko"; // 한국어 locale 임포트

dayjs.locale("ko");

type Kor1Type = {
  id: number;
  name: string;
  height: number;
  address: string;
  reason: string;
  fileLength: number;
};

type Kor2Type = {
  frtrlId: string;
  frtrlNm: string;
  mtnCd: string;
  ctpvNm: string;
  addrNm: string;
  lat: string;
  lot: string;
  aslAltide: string;
  crtrDt: string;
};

type MergedType = Kor1Type & Kor2Type;

export const mountains = (): MergedType[] => {
  return kor1
    .map((mountain) => {
      const matching = kor2.find((m) => m.frtrlNm === mountain.name);
      if (matching) {
        return { ...mountain, ...matching };
      }
      return null;
    })
    .filter((m): m is MergedType => m !== null);
};

export function createNumberList(n: number): number[] {
  return Array.from({ length: n }, (_, i) => i + 1);
}

export const isMobile = () => {
  return /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(
    navigator.userAgent
  );
};

export const toggleValue = (arr: number[], value: any): number[] => {
  // if (typeof value !== "string") return [];
  if (arr.includes(value)) {
    // 값이 이미 존재하면 해당 값을 제거
    return arr.filter((item) => item !== value);
  } else {
    // 값이 없으면 배열에 추가
    return [...arr, value];
  }
};

export const toFormattedDate = (timestamp: {
  seconds: number;
  nanoseconds: number;
}): any => {
  const ms = timestamp.seconds * 1000 + timestamp.nanoseconds / 1e6;
  return dayjs(ms);
};

/** 날짜를 수요일 오전 이런식으로 변환 */
export const formatDateKo = (dateString: string) => {
  // dayjs로 날짜 파싱 후 원하는 포맷으로 변환
  return dayjs(dateString).locale("ko").format("dddd A"); // 예: '수요일 오전 10:12'
};

/** 초단위 소요시간을 hh:mm:ss로 변환 */
export const formatDuration = (seconds: number) => {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const remainingSeconds = seconds % 60;
  return `${hours}:${minutes.toString().padStart(2, "0")}:${remainingSeconds
    .toString()
    .padStart(2, "0")}`;
};

